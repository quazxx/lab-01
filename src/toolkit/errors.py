"""Ошибки, которые команда показывает пользователю."""


class ToolkitError(Exception):
    """Ошибка калькулятора или конвертера."""


class CalculatorError(ToolkitError):
    """Выражение пустое, сломано или его нельзя посчитать."""


class ConverterError(ToolkitError):
    """Единица измерения неизвестна, разные группы или число не подходит."""
